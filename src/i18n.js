export function normalizeLang(value){
  const s=String(value??'').toLowerCase();
  return s.startsWith('zh')?'zh':s.startsWith('en')?'en':null;
}

// ?lang= wins, then the saved choice, then the browser language; anything
// that is not Chinese falls back to English.
export function detectLang({search='',stored=null,nav=''}={}){
  return normalizeLang(new URLSearchParams(search).get('lang'))||normalizeLang(stored)||normalizeLang(nav)||'en';
}

export function translate(lang,text,vars){
  if(typeof text!=='string')return text;
  const s=lang==='en'?(EN[text]??text):text;
  return vars?s.replace(/\{(\w+)\}/g,(m,k)=>k in vars?String(vars[k]):m):s;
}

