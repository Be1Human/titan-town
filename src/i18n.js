const clean=s=>s.replace(/[\s\u00a0]+/g,' ').trim();

// Static markup is authored in Chinese; translate its text and labels once.
export function applyDom(doc=document){
  doc.documentElement.lang=lang==='en'?'en':'zh-CN';
  if(lang!=='en')return;
  const walker=doc.createTreeWalker(doc.documentElement,4);
  const nodes=[];for(let n=walker.nextNode();n;n=walker.nextNode())nodes.push(n);
  for(const node of nodes){
    if(/^(SCRIPT|STYLE)$/.test(node.parentNode?.nodeName))continue;
    const key=clean(node.nodeValue);if(!key||!(key in EN))continue;
    node.nodeValue=node.nodeValue.replace(/\S(?:[\s\S]*\S)?/,EN[key]);
  }
  for(const el of doc.querySelectorAll('[aria-label],[title]'))for(const a of ['aria-label','title']){
    const v=el.getAttribute(a);if(v&&clean(v) in EN)el.setAttribute(a,EN[clean(v)]);
  }
}

// Menu button: remembers the choice and reloads with ?lang= updated.
export function bindLangToggle(doc=document){
  const button=doc.getElementById('lang-toggle');if(!button)return;
  const next=lang==='en'?'zh':'en';
  button.textContent=next==='en'?'English':'中文';
  button.onclick=()=>{
    try{localStorage.setItem(STORE_KEY,next);}catch{}
    const url=new URL(location.href);url.searchParams.set('lang',next);location.href=url.toString();
  };
}
